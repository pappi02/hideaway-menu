/**
 * Downloads the chapter photography at full resolution and writes the credits.
 *
 * Images are sourced through the Openverse index and restricted to CC0 and
 * Public Domain Mark, so they can be used commercially with no attribution
 * obligation. `IMAGE_CREDITS.md` records the provenance anyway: a menu is a
 * commercial document and the hotel should be able to prove where every asset
 * came from.
 *
 * These are placeholders. Replace them with the hotel's own photography.
 *
 * Usage: node scripts/fetch-images.mjs <selection.json>
 * where selection.json maps output filename -> Openverse image id.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public', 'images', 'menu');
const UA = 'hideaway-menu-image-sourcing/1.0';

async function get(url, tries = 5) {
  for (let i = 0; i < tries; i += 1) {
    try {
      const r = await fetch(url, {
        headers: { 'User-Agent': UA },
        signal: AbortSignal.timeout(60000),
      });
      if (r.ok) return r;
    } catch {
      /* retry */
    }
    await new Promise((res) => setTimeout(res, 1500 * (i + 1)));
  }
  return null;
}

const selection = JSON.parse(await fs.readFile(process.argv[2], 'utf8'));
await fs.mkdir(OUT, { recursive: true });

const rows = [];

for (const [file, id] of Object.entries(selection)) {
  if (!id) continue;

  const meta = await get(`https://api.openverse.org/v1/images/${id}/`);
  if (!meta) {
    console.error(`${file}: could not read metadata`);
    continue;
  }
  const info = await meta.json();

  const image = await get(info.url);
  if (!image) {
    console.error(`${file}: could not download ${info.url}`);
    continue;
  }

  const bytes = Buffer.from(await image.arrayBuffer());
  await fs.writeFile(path.join(OUT, file), bytes);

  rows.push({
    file,
    title: info.title,
    creator: info.creator,
    licence: `${info.license.toUpperCase()} ${info.license_version}`,
    licenceUrl: info.license_url,
    source: info.foreign_landing_url,
    dims: `${info.width}x${info.height}`,
  });

  console.log(`${file}  ${(bytes.length / 1024).toFixed(0)} KB  ${info.width}x${info.height}`);
}

const credits = [
  '# Image credits',
  '',
  'Every image shipped with this menu is Public Domain Mark or CC0 — free for',
  'commercial use with no attribution required. The credits are recorded here',
  'regardless, so the hotel can show provenance for anything on the menu.',
  '',
  '**These are placeholders.** Replace them with the hotel’s own photography:',
  'drop a file into `public/images/menu/` under the same name and nothing else',
  'needs to change.',
  '',
  '| File | Title | Creator | Licence | Source |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| \`${r.file}\` | ${r.title ?? '—'} | ${r.creator ?? '—'} | [${r.licence}](${r.licenceUrl}) | [link](${r.source}) |`,
  ),
  '',
  '## Not sourced here',
  '',
  'The following were supplied with the original project and are not covered by',
  'the table above. Confirm their licensing before the menu goes live:',
  '',
  '- `resort.jpg` (the original cover image, now used on the reservations page),',
  '  `kenyan-classics.jpg`, `grill.jpg`, `seafood.jpg`, `desserts.jpg`,',
  '  `spa.jpg`, `grooming.jpg`',
  '',
  `_Generated by \`scripts/fetch-images.mjs\` on ${new Date().toISOString().slice(0, 10)}._`,
  '',
].join('\n');

await fs.writeFile(path.join(ROOT, 'IMAGE_CREDITS.md'), credits, 'utf8');
console.log(`\n${rows.length} images, credits written to IMAGE_CREDITS.md`);
